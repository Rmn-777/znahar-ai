/**
 * The provenance note composer — the spec's §4 format.
 *
 * Every interactive note carries three visually distinct layers:
 *
 *   > [!SOURCE] Исходник — Telegram, …        ← the material as it arrived
 *   ## Мои мысли                              ← the user's own additions, when any
 *   > [!AI] Обработка ИИ — Конспект (gemini)  ← what the model added, when it did
 *
 * plus a frontmatter block that makes the note queryable (source, type, action,
 * provider, status) and traceable (the telegram ids the pipeline already stamps).
 * Callout names and the inbox folder come from settings; empty layers are omitted —
 * a «Сохранить как есть» note has no AI callout, a fresh note has no thoughts.
 */

import TelegramBot from "src/telegram/botApi";
import TelegramSyncPlugin from "src/main";
import { t } from "src/locale/i18n";
import { formatDateTime, messageTimestampMs, unixTime2Date } from "src/utils/dateUtils";
import { neutralizeLeadingFrontmatter } from "src/utils/frontmatterUtils";
import type { InteractiveEntry } from "./types";
import { getAction } from "./catalog";

export interface ComposerSettings {
	/** Head of the callout wrapping the source material. */
	interactiveSourceCallout: string;
	/** Head of the callout wrapping the AI result. */
	interactiveAICallout: string;
}

/** YAML frontmatter block built from ordered fields; strings JSON-quoted (valid YAML). */
export function buildFrontmatter(fields: [string, string | number | string[]][]): string {
	const lines = fields.map(([key, value]) => {
		if (Array.isArray(value)) {
			if (value.length === 0) return `${key}: []`;
			return `${key}:\n${value.map((item) => `  - ${yamlScalar(item)}`).join("\n")}`;
		}
		return `${key}: ${yamlScalar(value)}`;
	});
	return `---\n${lines.join("\n")}\n---`;
}

function yamlScalar(value: string | number): string {
	return typeof value === "number" ? String(value) : JSON.stringify(value);
}

/** The action label for the AI callout, e.g. "Конспект" — from the same locale key as the menu. */
function actionTitle(actionId: string | undefined, provider: string | undefined): string | null {
	if (!actionId || provider === "none") return null;
	const action = getAction(actionId);
	if (!action) return actionId;
	return t(`interactive.actions.${action.id}`);
}

/**
 * The note body: SOURCE callout, thoughts section, AI callout — each layer only when
 * it holds content. `sourceText` is neutralized against a leading YAML block the same
 * way every other rendered message text is.
 */
export function composeNoteBody(
	plugin: TelegramSyncPlugin,
	msg: TelegramBot.Message,
	entry: Pick<InteractiveEntry, "source" | "result" | "actionId" | "provider" | "thoughts">,
): string {
	const settings = plugin.settings as unknown as ComposerSettings;
	const sourceCallout = settings.interactiveSourceCallout || "SOURCE";
	const aiCallout = settings.interactiveAICallout || "AI";
	const when = formatDateTime(unixTime2Date(msg.date), "DD.MM.YYYY HH:mm");

	const layers: string[] = [];

	// Layer 1 — the source material.
	const sourceText = neutralizeLeadingFrontmatter(entry.source?.sourceText || "").trim();
	const sourceLines = [
		`> [!${sourceCallout}] ${"Исходник — Telegram"}, ${when}`,
		...(sourceText ? quoteBlock(sourceText) : ["_>пусто_"]),
	];
	if (entry.source?.filePath) {
		// Attachment embeds go right after the callout, so the file sits with its source.
		const name = entry.source.filePath.split("/").pop() || entry.source.filePath;
		sourceLines.push(`> ![[${name}]]`);
	}
	layers.push(sourceLines.join("\n"));

	// Layer 2 — the user's own additions. Hidden until they add any.
	if (entry.thoughts.length > 0) {
		layers.push(`## Мои мысли\n\n${entry.thoughts.map((thought) => `- ${thought}`).join("\n")}`);
	}

	// Layer 3 — the AI result, with the action and provider that produced it.
	const title = actionTitle(entry.actionId, entry.provider);
	if (title && entry.result?.trim()) {
		const resultText = neutralizeLeadingFrontmatter(entry.result).trim();
		layers.push(
			[`> [!${aiCallout}] Обработка ИИ — ${title} (${entry.provider})`, ...quoteBlock(resultText)].join("\n"),
		);
	}

	return layers.join("\n\n");
}

/** Quotes every line of a block for use inside a callout; blank lines become bare ">". */
function quoteBlock(text: string): string[] {
	return text.split("\n").map((line) => (line.trim() ? `> ${line}` : ">"));
}

/**
 * Full note content: frontmatter first, body after. `title` is generated by the flow
 * (AI metadata or fallback) and passed in — the composer never calls the model.
 */
export function composeNote(
	plugin: TelegramSyncPlugin,
	msg: TelegramBot.Message,
	entry: InteractiveEntry,
	title: string,
): string {
	const settings = plugin.settings as unknown as ComposerSettings & { noteFrontmatterIds?: boolean };
	const frontmatter: [string, string | number | string[]][] = [
		["title", title],
		["source", "telegram"],
		["type", entry.source?.contentType ?? "unknown"],
		// Deterministic, unlike unixTime2Date: a field meant for Dataview queries must not
		// drift by the current wall-clock milliseconds on every render.
		["collected", new Date(messageTimestampMs(msg.date)).toISOString()],
		["action", entry.actionId ?? "none"],
		["provider", entry.provider ?? "none"],
		["status", "inbox"],
		["tags", []],
	];
	if (settings.noteFrontmatterIds) {
		frontmatter.push(
			["telegram-chat-id", msg.chat.id],
			["telegram-message-id", msg.message_id],
			["telegram-date", unixTime2Date(msg.date).toISOString()],
		);
	}
	return `${buildFrontmatter(frontmatter)}\n\n${composeNoteBody(plugin, msg, entry)}\n`;
}
